  stance = "APPROVE",
  match_source = "approve_exact",
  matched_pattern = c("sí", "yes", "oui", "agree", "sim", "approve", "apruebo"),
  canonical_pattern = c("sí", "yes", "oui", "agree", "sim", "approve", "apruebo"),
  match_type = "exact",
  stringsAsFactors = FALSE
)
sorting_rows <- build_stance_heuristic_rows(
  sorting_registry,
  "APPROVE",
  terms_per_row = 20
)
sorting_terms <- paste(sorting_rows$terms, collapse = "\n")
assert_contains(
  sorting_terms,
  "English: agree, approve, yes",
  "english display group sorted alphabetically"
)
assert_contains(
  sorting_terms,
  "Non-English: apruebo, oui, sim, sí",
  "non-english display group sorted alphabetically"
)
english_pos <- regexpr("English: agree, approve, yes", sorting_terms, fixed = TRUE)[[1]]
non_english_pos <- regexpr("Non-English: apruebo, oui, sim, sí", sorting_terms, fixed = TRUE)[[1]]
stopifnot(english_pos > 0L)
stopifnot(non_english_pos > english_pos)

