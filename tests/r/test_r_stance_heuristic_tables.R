assert_contains <- function(text, pattern, label, fixed = TRUE) {
  if (!grepl(pattern, text, fixed = fixed)) {
    stop(paste("Missing", label, "pattern:", pattern))
  }
}

assert_not_contains <- function(text, pattern, label, fixed = TRUE) {
  if (grepl(pattern, text, fixed = fixed)) {
    stop(paste("Unexpected", label, "pattern:", pattern))
  }
}

